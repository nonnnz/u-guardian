// Visual and interaction acceptance on an isolated demo server; no provider credentials.
const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const base=process.env.BASE_URL||'http://127.0.0.1:4186';
(async()=>{
 const browser=await chromium.launch({headless:true,channel:'msedge'});
 try{
  const page=await browser.newPage({viewport:{width:1440,height:960}}),errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto(base);
  await page.waitForFunction(()=>document.querySelector('u-guardian').state&&!document.querySelector('u-guardian').busy);
  await page.evaluate(async()=>{const w=document.querySelector('u-guardian');for(const rule of w.guardian.rules.filter(r=>r.active))await w.request('agent/watch/remove',{id:rule.id});w.acceptState(await w.request('reset',{}));w.dismissAlerts();});
  await page.evaluate(()=>document.fonts.ready);
  assert.equal(await page.evaluate(()=>document.fonts.check('16px Manrope')),true);
  assert.equal((await page.request.get(base+'/fonts/manrope-variable.ttf')).headers()['content-type'],'font/ttf');
  fs.mkdirSync('.impeccable/review',{recursive:true});
  const shot=async name=>{await page.waitForTimeout(450);await page.screenshot({path:'.impeccable/review/orange-'+name+'.png',fullPage:true,animations:'disabled'});};
  await shot('desktop');
  await page.locator('#open-settings').click();
  await shot('settings-desktop');
  await page.locator('[data-section=connections-section]').click();
  await page.waitForFunction(()=>document.querySelector('[data-section=connections-section]').getAttribute('aria-current')==='true');
  await page.locator('.provider').first().locator('summary').first().click();
  await shot('connections-desktop');
  await page.locator('[data-section=goals-section]').click();
  assert.equal(await page.locator('#goals-section').evaluate(e=>e.open),true);
  await page.locator('[data-section=mapping-section]').click();
  assert.equal(await page.locator('#mapping-section').evaluate(e=>e.open),true);
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('#open-settings').evaluate(e=>e===document.activeElement),true);
  await page.locator('u-guardian #launcher').click();
  await shot('chat-desktop');
  assert.equal(await page.locator('u-guardian #suggestions').isVisible(),false);
  await page.locator('u-guardian #chat-options > summary').click();
  await shot('chat-options-desktop');
  await page.locator('u-guardian #open-watches').click();
  assert.equal(await page.locator('u-guardian #watch-panel').isVisible(),true);
  await shot('watches-desktop');
  await page.locator('u-guardian #back-chat').click();
  await page.evaluate(()=>{const w=document.querySelector('u-guardian');window.mascotPhases=[];w.addEventListener('guardian:phase',e=>window.mascotPhases.push(e.detail.mascotState));});
  await page.locator('u-guardian #input').fill('Check my wallet health.');
  await page.locator('u-guardian #send').click();
  await page.waitForFunction(()=>!document.querySelector('u-guardian').busy);
  assert.match(await page.locator('u-guardian .assistant').last().textContent(),/57%/);
  assert.equal(await page.locator('u-guardian .stage').isVisible(),true);
  assert.equal(await page.locator('u-guardian #mascot').isVisible(),true);
  assert.equal(await page.evaluate(()=>window.mascotPhases.includes('search')&&window.mascotPhases.includes('answer')),true);
  assert.equal(await page.locator('u-guardian .answer-details').last().evaluate(e=>e.open),false);
  await shot('answer-desktop');
  await page.keyboard.press('Escape');
  await page.waitForFunction(()=>{const e=document.querySelector('u-guardian').shadowRoot.querySelector('#launcher');return e===e.getRootNode().activeElement;});
  await page.setViewportSize({width:390,height:844});
  await page.evaluate(()=>document.querySelector('u-guardian').dismissAlerts());
  await page.locator('#language').focus();
  await shot('mobile');
  await page.locator('#open-settings').click();
  await page.locator('[data-section=wallet-section]').click();
  await page.waitForFunction(()=>document.querySelector('[data-section=wallet-section]').getAttribute('aria-current')==='true');
  await shot('settings-mobile');
  assert.equal(await page.locator('#settings').evaluate(e=>e.scrollWidth>e.clientWidth),false);
  await page.keyboard.press('Escape');
  await page.locator('u-guardian #launcher').click();
  await shot('chat-mobile');
  assert.equal(await page.locator('u-guardian #chat-dialog').evaluate(e=>e.scrollWidth>e.clientWidth),false);
  await page.keyboard.press('Escape');
  await page.locator('#language').selectOption('th');
  await page.waitForFunction(()=>document.documentElement.lang==='th'&&document.querySelector('u-guardian').state&&!document.querySelector('u-guardian').busy);
  await page.evaluate(()=>document.querySelector('u-guardian').dismissAlerts());
  await shot('thai-mobile');
  await page.locator('#open-settings').click();await shot('thai-settings-mobile');await page.keyboard.press('Escape');
  await page.locator('u-guardian #launcher').click();await shot('thai-chat-mobile');await page.keyboard.press('Escape');
  await page.emulateMedia({reducedMotion:'reduce'});
  assert.equal(await page.locator('u-guardian .perched').evaluate(e=>getComputedStyle(e).animationName),'none');
  assert.equal(await page.locator('.wallet').evaluate(e=>getComputedStyle(e).animationName),'none');
  await page.setViewportSize({width:320,height:700});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  const noLauncherCollision=async()=>{
   assert.equal(await page.evaluate(()=>{const label=document.querySelector('u-guardian').shadowRoot.querySelector('.launcher-label').getBoundingClientRect();return ['mode','wallet-title'].every(id=>{const box=document.getElementById(id).getBoundingClientRect();return box.bottom<=label.top||box.top>=label.bottom||box.right<=label.left||box.left>=label.right;});}),true,'Wallet heading and mode must not collide with the mascot label');
  };
  await noLauncherCollision();await shot('thai-mobile-320');
  await page.setViewportSize({width:390,height:844});await noLauncherCollision();
  await page.locator('#language').selectOption('en');
  await page.waitForFunction(()=>document.documentElement.lang==='en'&&document.querySelector('u-guardian').state&&!document.querySelector('u-guardian').busy);
  await page.evaluate(()=>document.querySelector('u-guardian').dismissAlerts());
  await noLauncherCollision();
  await page.setViewportSize({width:320,height:700});await noLauncherCollision();await shot('mobile-320');
  assert.deepEqual(errors,[]);
  console.log('PASS orange UI: font loading, section navigation, disclosures, focus return, real demo answer, English/Thai layouts, 320px overflow, reduced motion; screenshots captured.');
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exit(1);});
